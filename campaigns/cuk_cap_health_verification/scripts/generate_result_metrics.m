function metrics = generate_result_metrics(rootDir)
%GENERATE_RESULT_METRICS Normalize all verification outputs to one schema.

if nargin<1, rootDir=fileparts(fileparts(mfilename("fullpath"))); end
resultDir=fullfile(rootDir,"results"); tableDir=fullfile(resultDir,"tables");
p=model_parameters();
names=["test_id","model_type","Vin","D","load_percent","fs_Hz", ...
    "C_true_F","ESR_true_Ohm","noise_SNR_dB","adc_bits", ...
    "samples_per_cycle","sync_error_s","ESL_H","method","C_est_F", ...
    "C_MAPE_percent","ESR_est_Ohm","ESR_MAPE_percent", ...
    "convergence_time_s","rank_Phi","cond_Phi","rank_Obs", ...
    "cond_Obs","min_singular_Obs","status","notes"];
types=["string","string",repmat("double",1,11),"string", ...
    repmat("double",1,10),"string","string"];
metrics=table('Size',[0,numel(names)],'VariableTypes',types, ...
    'VariableNames',names);

%% Ideal Model A and independent circuit Model B.
I=load(fullfile(resultDir,"ideal","ideal_validation.mat"),"summary");
metrics=append_row(metrics,"IDEAL_RLS","Model_A",p,p.C1,I.summary.rlsCMape, ...
    p.ESR,I.summary.rlsRMape,I.summary.rlsConvergence,I.summary.rankPhi, ...
    I.summary.condGramNormalized,NaN,NaN,NaN,"RLS","PASS","Ideal switched equations");
metrics=append_row(metrics,"IDEAL_KF","Model_A",p,p.C1,I.summary.kfCMape, ...
    p.ESR,I.summary.kfRMape,I.summary.kfConvergence,I.summary.rankPhi, ...
    I.summary.condGramNormalized,NaN,NaN,NaN,"TS_LTVKF","PASS","Ideal switched equations");
B=load(fullfile(resultDir,"model_b","model_cross_validation.mat"),"summary");
metrics=append_row(metrics,"MODELB_RLS","Model_B_Simscape",p,p.C1,B.summary.rlsCMape, ...
    p.ESR,B.summary.rlsESRMape,NaN,2,NaN,NaN,NaN,NaN,"RLS","PASS", ...
    "Independent Simscape circuit");
metrics=append_row(metrics,"MODELB_KF","Model_B_Simscape",p,p.C1,B.summary.kfCMape, ...
    p.ESR,B.summary.kfESRMape,NaN,2,NaN,NaN,NaN,NaN,"TS_LTVKF","PASS", ...
    "Independent Simscape circuit");

%% Operating sweep: preserve CCM exclusions and the adaptive covariance result.
O=readtable(fullfile(tableDir,"result_operating_sweep.csv"),"TextType","string");
for k=1:height(O)
    local=p; local.Vin=O.Vin_V(k); local.D=O.D(k); local.Rload=O.Rload_Ohm(k);
    if O.status(k)=="CCM"
        methods=["RLS","TS_LTVKF_adaptive"];
        ce=[O.RLS_C_MAPE_percent(k),O.LTVKF_adaptive_C_MAPE_percent(k)];
        re=[O.RLS_ESR_MAPE_percent(k),O.LTVKF_adaptive_ESR_MAPE_percent(k)];
        cv=[NaN,O.LTVKF_convergence_s(k)];
        for m=1:2
            state=pass_fail(ce(m),re(m));
            metrics=append_row(metrics,"OP_"+k+"_"+m,"Model_A",local, ...
                NaN,ce(m),NaN,re(m),cv(m),O.rank_Phi(k), ...
                O.cond_Phi_normalized(k),O.rank_Obs(k),O.cond_Obs(k), ...
                O.min_singular_Obs(k),methods(m),state, ...
                "CCM operating sweep; load fraction="+O.load_fraction(k));
        end
    else
        metrics=append_row(metrics,"OP_"+k+"_DCM","Model_A",local, ...
            NaN,NaN,NaN,NaN,NaN,O.rank_Phi(k),O.cond_Phi_normalized(k), ...
            NaN,NaN,NaN,"not_evaluated","EXCLUDED_DCM", ...
            "Estimator claims scoped to CCM; load fraction="+O.load_fraction(k));
    end
end

%% Monte Carlo aggregate rows (all sensors, both explicit SNR definitions).
N=readtable(fullfile(tableDir,"table_noise_monte_carlo.csv"),"TextType","string");
N=N(N.noise_target=="all",:);
for k=1:height(N)
    state=pass_fail(N.C_MAPE_median_percent(k),N.ESR_MAPE_median_percent(k));
    if N.failure_rate(k)>0, state="FAIL"; end
    note=N.snr_reference(k)+"; median of 20 seeds; failure_rate="+N.failure_rate(k);
    metrics=append_custom(metrics,"NOISE_"+k,"Model_A_noise",p.Vin,p.D,100, ...
        p.fs,p.C1,p.ESR,N.SNR_dB(k),NaN,200,NaN,0,N.method(k),NaN, ...
        N.C_MAPE_median_percent(k),NaN,N.ESR_MAPE_median_percent(k), ...
        NaN,NaN,NaN,NaN,NaN,NaN,state,note);
end

%% ADC and synchronous-sampling sweeps.
A=readtable(fullfile(tableDir,"table_adc_sampling.csv"),"TextType","string");
for k=1:height(A)
    metrics=append_custom(metrics,"ADC_"+A.test_id(k),"Model_A_quantized", ...
        p.Vin,p.D,100,p.fs,p.C1,p.ESR,NaN,A.adc_bits(k), ...
        A.samples_per_cycle(k),0,0,A.method(k),A.C_est_F(k), ...
        A.C_MAPE_percent(k),A.ESR_est_Ohm(k),A.ESR_MAPE_percent(k), ...
        A.convergence_time_s(k),A.rank_Phi(k),NaN,NaN,NaN,NaN, ...
        pass_fail(A.C_MAPE_percent(k),A.ESR_MAPE_percent(k)), ...
        "Voltage range 0-100 V; current range +/-5 A");
end
S=readtable(fullfile(tableDir,"table_sync_error.csv"));
for k=1:height(S)
    methods=["RLS","TS_LTVKF"];
    ce=[S.RLS_C_MAPE_percent(k),S.LTVKF_C_MAPE_percent(k)];
    re=[S.RLS_ESR_MAPE_percent(k),S.LTVKF_ESR_MAPE_percent(k)];
    for m=1:2
        metrics=append_custom(metrics,"SYNC_"+k+"_"+m,"Model_A_sync", ...
            p.Vin,p.D,100,p.fs,p.C1,p.ESR,NaN,NaN,1000,S.sync_error_s(k), ...
            0,methods(m),NaN,ce(m),NaN,re(m),NaN,S.rank_Phi(k),NaN, ...
            NaN,NaN,NaN,pass_fail(ce(m),re(m)), ...
            "Offset="+S.sync_error_over_Ts(k)+" Ts; adjacent-edge assignment");
    end
end

%% Dynamic and transient results.
D=readtable(fullfile(tableDir,"table_dynamic_tracking.csv"),"TextType","string");
for k=1:height(D)
    ce=abs(D.C_settled_bias_percent(k)); re=abs(D.ESR_settled_bias_percent(k));
    conv=max([D.C_tracking_10_90_s(k),D.ESR_tracking_10_90_s(k)],[],"omitnan");
    if isempty(conv)||isinf(conv), conv=NaN; end
    metrics=append_custom(metrics,"DYN_"+k,"Model_A_dynamic",p.Vin,p.D,100, ...
        p.fs,D.C_final_F(k),D.ESR_final_Ohm(k),NaN,NaN,200,0,0,D.method(k), ...
        D.C_final_F(k)*(1+D.C_settled_bias_percent(k)/100),ce, ...
        D.ESR_final_Ohm(k)*(1+D.ESR_settled_bias_percent(k)/100),re,conv, ...
        NaN,NaN,NaN,NaN,NaN,pass_fail(ce,re),D.scenario(k));
end

%% Conduction nonidealities and ESL/ringing edge estimators.
NI=readtable(fullfile(tableDir,"table_nonideal_tests.csv"),"TextType","string");
for k=1:height(NI)
    metrics=append_custom(metrics,"NONIDEAL_"+k,"Model_A_nonideal",p.Vin,p.D, ...
        100,p.fs,p.C1,p.ESR,NaN,NaN,200,0,0,NI.method(k),NI.C_est_F(k), ...
        NI.C_MAPE_percent(k),NI.ESR_est_Ohm(k),NI.ESR_MAPE_percent(k), ...
        NaN,2,NaN,NaN,NaN,NaN,pass_fail(NI.C_MAPE_percent(k), ...
        NI.ESR_MAPE_percent(k)),NI.scenario(k));
end
E=readtable(fullfile(tableDir,"table_edge_method_comparison.csv"),"TextType","string");
for k=1:height(E)
    state="PASS"; if E.ESR_MAPE_percent(k)>5, state="FAIL"; end
    metrics=append_custom(metrics,"EDGE_ESL_"+k,"Model_A_ESL_ringing", ...
        p.Vin,p.D,100,p.fs,p.C1,p.ESR,NaN,NaN,200,0,E.ESL_H(k), ...
        E.method(k),NaN,NaN,E.ESR_est_mean_Ohm(k),E.ESR_MAPE_percent(k), ...
        NaN,NaN,NaN,NaN,NaN,NaN,state,"120 rising edges");
end

writetable(metrics,fullfile(tableDir,"result_metrics.csv"));
fprintf('Wrote %d normalized metric rows to result_metrics.csv\n',height(metrics));
end

function tableOut=append_row(tableIn,id,model,p,Cest,Cerr,Rest,Rerr,conv, ...
    rankPhi,condPhi,rankObs,condObs,sigmaObs,method,status,notes)
tableOut=append_custom(tableIn,id,model,p.Vin,p.D,100,p.fs,p.C1,p.ESR, ...
    NaN,NaN,200,0,p.ESL,method,Cest,Cerr,Rest,Rerr,conv,rankPhi,condPhi, ...
    rankObs,condObs,sigmaObs,status,notes);
end

function tableOut=append_custom(tableIn,id,model,Vin,D,loadPercent,fs,Ctrue, ...
    Rtrue,snr,bits,spp,sync,esl,method,Cest,Cerr,Rest,Rerr,conv,rankPhi, ...
    condPhi,rankObs,condObs,sigmaObs,status,notes)
tableIn(end+1,:)={string(id),string(model),Vin,D,loadPercent,fs,Ctrue,Rtrue, ...
    snr,bits,spp,sync,esl,string(method),Cest,Cerr,Rest,Rerr,conv,rankPhi, ...
    condPhi,rankObs,condObs,sigmaObs,string(status),string(notes)};
tableOut=tableIn;
end

function state=pass_fail(cError,rError)
if isfinite(cError)&&isfinite(rError)&&cError<=3&&rError<=5
    state="PASS";
else
    state="FAIL";
end
end
