function [rows, cache] = runFactorial(cases, cfg)
nConditions = height(cases) * numel(cfg.noiseNames) * numel(cfg.skewNs);
nRows = nConditions * numel(cfg.observations) * numel(cfg.estimators);
template = struct( ...
    "case_id", "", "noise_profile", "", "skew_ns", 0, "seed", 0, ...
    "observation", "", "estimator", "", "cell_id", "", ...
    "C_true_F", 0, "ESR_true_ohm", 0, "C_est_F", 0, ...
    "ESR_est_ohm", 0, "C_error_percent", 0, ...
    "ESR_error_percent", 0, "C_bias_percent", 0, ...
    "ESR_bias_percent", 0, "C_variance", 0, "ESR_variance", 0, ...
    "convergence_cycles", 0, "divergence_flag", false, ...
    "projection_saturation", false, "projection_activations", 0, ...
    "invalid_updates", 0, "timing_failure", false, ...
    "nis_mean", NaN, "nees_parameter", NaN, ...
    "CI_C_contains_true", false, "CI_ESR_contains_true", false, ...
    "mu_C", 0, "mu_R", 0);
data = repmat(template, nRows, 1);
cache = cell(nConditions, 1);
row = 0;
condition = 0;
for iCase = 1:height(cases)
    for iNoise = 1:numel(cfg.noiseNames)
        for iSkew = 1:numel(cfg.skewNs)
            condition = condition + 1;
            seed = cases.seed(iCase) + 1000 * (iNoise - 1) + ...
                10000 * (iSkew - 1);
            obs = simulateObservation(cases(iCase, :), iNoise, ...
                cfg.skewNs(iSkew), seed, cfg);
            cache{condition} = struct("case_id", cases.case_id(iCase), ...
                "noise", cfg.noiseNames(iNoise), ...
                "skew_ns", cfg.skewNs(iSkew), "seed", seed);
            for iObservation = 1:numel(cfg.observations)
                for iEstimator = 1:numel(cfg.estimators)
                    row = row + 1;
                    est = runEstimator(obs, iObservation, iEstimator, ...
                        true, cfg);
                    data(row) = makeFactorialRow(cases.case_id(iCase), ...
                        cfg.noiseNames(iNoise), cfg.skewNs(iSkew), ...
                        seed, cfg.observations(iObservation), ...
                        cfg.estimators(iEstimator), obs, est, cfg);
                end
            end
        end
    end
end
rows = struct2table(data);
rows = sortrows(rows, ["case_id", "noise_profile", "skew_ns", ...
    "estimator", "observation"]);
end

function row = makeFactorialRow(caseId, noiseName, skewNs, seed, ...
        observation, estimator, obs, est, cfg)
Ctrue = obs.Ctruth(end);
Rtrue = obs.Rtruth(end);
Cest = cfg.Cb / est.theta(1);
Rest = est.theta(2);
Cerr = 100 * abs(Cest / Ctrue - 1);
Rerr = 100 * abs(Rest / Rtrue - 1);
failed = ~all(isfinite([Cest, Rest, est.varC, est.varR])) || ...
    Cest <= 0 || Rest <= 0 || Cerr > 50 || Rerr > 50;
timingFailure = skewNs >= 50 && (Rerr > 5 || failed);
alphaError = est.theta(1) - cfg.Cb / Ctrue;
rError = Rest - Rtrue;
P = est.P;
nees = [alphaError, rError] * pinv(P) * [alphaError; rError];
sigmaC = cfg.Cb / max(est.theta(1)^2, eps) * ...
    sqrt(max(P(1, 1), 0));
sigmaR = sqrt(max(P(2, 2), 0));
row = struct( ...
    "case_id", string(caseId), "noise_profile", string(noiseName), ...
    "skew_ns", skewNs, "seed", seed, ...
    "observation", string(observation), ...
    "estimator", string(estimator), ...
    "cell_id", extractBefore(string(observation), " ") + "-" + ...
        extractBefore(string(estimator), " "), ...
    "C_true_F", Ctrue, "ESR_true_ohm", Rtrue, ...
    "C_est_F", Cest, "ESR_est_ohm", Rest, ...
    "C_error_percent", Cerr, "ESR_error_percent", Rerr, ...
    "C_bias_percent", 100 * (Cest / Ctrue - 1), ...
    "ESR_bias_percent", 100 * (Rest / Rtrue - 1), ...
    "C_variance", est.varC, "ESR_variance", est.varR, ...
    "convergence_cycles", est.convergence, ...
    "divergence_flag", failed, ...
    "projection_saturation", est.projectionActivations > 0, ...
    "projection_activations", est.projectionActivations, ...
    "invalid_updates", est.invalidUpdates, ...
    "timing_failure", timingFailure, "nis_mean", est.nisMean, ...
    "nees_parameter", nees, ...
    "CI_C_contains_true", abs(Cest - Ctrue) <= 1.96 * sigmaC, ...
    "CI_ESR_contains_true", abs(Rest - Rtrue) <= 1.96 * sigmaR, ...
    "mu_C", obs.muC, "mu_R", obs.muR);
end

function obs = simulateObservation(caseRow, iNoise, skewNs, seed, cfg)
rng(seed, "twister");
n = cfg.nSamples;
k = (1:n).';
phase = 2 * pi * k / 37 + 0.17 * caseRow.duty;
Ctrue = cfg.Cb * caseRow.C_factor;
Rtrue = cfg.Rb * caseRow.ESR_factor;
alphaTrue = cfg.Cb / Ctrue;
currentScale = 2.45 * caseRow.load_factor * (caseRow.Vin_V / 24) * ...
    (0.72 + 1.35 * caseRow.duty) / (0.72 + 1.35 * 0.45);
iSum = currentScale .* (1 + 0.13 * sin(phase) + ...
    0.04 * sin(3 * phase + 0.5));
iSum = max(iSum, 0.12);
hC = sqrt(caseRow.load_factor) .* ...
    (0.040 + 0.025 * caseRow.duty) .* ...
    (1 + 0.38 * sin(phase + 0.3) + 0.08 * cos(5 * phase));
hC = max(abs(hC), 0.012) .* sign(hC + eps);
hR = iSum;
sigmaV = cfg.sigmaV(iNoise);
sigmaI = cfg.sigmaI(iNoise);
commonNoise = sigmaV * randn(n, 1);
nC = 0.72 * commonNoise + 0.70 * sigmaV * randn(n, 1) + ...
    sigmaI * 0.08 .* randn(n, 1);
nR = 0.54 * commonNoise + 0.84 * sigmaV * randn(n, 1) + ...
    sigmaI * Rtrue .* randn(n, 1);
modelC = (0.0018 + 0.0012 * abs(caseRow.duty - 0.48)) .* ...
    hC .* sin(2 * phase + 0.2);
kRtrue = cfg.kRCalibration + 0.006 * ...
    sin(2 * pi * double(caseRow.seed) / 17);
skewS = skewNs * 1e-9;
edgeSlope = 8.0e4 * (caseRow.Vin_V / 24);
residualSkew = edgeSlope .* sin(phase + 0.7) .* skewS;
rawSkew = edgeSlope .* (0.65 + 0.35 * sin(phase + 0.7)) .* ...
    (85e-9 + skewS);
hMixedR = 0.62 .* iSum .* sin(phase + 0.9);
zC = hC .* alphaTrue + modelC + nC;
zR = kRtrue .* hR .* Rtrue + residualSkew + nR;
zMixed = hC .* alphaTrue + hMixedR .* Rtrue + modelC + ...
    0.55 .* nC + 0.45 .* nR + 0.62 .* rawSkew;
qDyn = cfg.Cb .* ...
    (0.010 + 0.023 * sin(phase) + 0.008 * cos(2 * phase));
iCap = currentScale .* sign(sin(phase + 0.1)) .* ...
    (0.75 + 0.20 * sin(4 * phase));
vIdeal = zeros(n, 1);
vIdeal(1) = 36 + 0.5 * caseRow.duty;
for j = 2:n
    vIdeal(j) = vIdeal(j - 1) + qDyn(j - 1) / Ctrue;
end
yTerminal = vIdeal + Rtrue .* iCap + sigmaV .* randn(n, 1) + ...
    0.20 .* residualSkew .* sign(iCap);
RC = max(2 * sigmaV^2, 1e-8);
RR = max(2 * sigmaV^2 + (sigmaI * Rtrue)^2, 1e-8);
R0 = RC + RR;
obs = struct("hC", hC, "hR", hR, "hMixedR", hMixedR, ...
    "zC", zC, "zR", zR, "zMixed", zMixed, ...
    "qDyn", qDyn, "iCap", iCap, "yTerminal", yTerminal, ...
    "Ctruth", repmat(Ctrue, n, 1), ...
    "Rtruth", repmat(Rtrue, n, 1), ...
    "alphaTruth", repmat(alphaTrue, n, 1), ...
    "Cinit", Ctrue * caseRow.C_init_factor, ...
    "Rinit", Rtrue * caseRow.ESR_init_factor, ...
    "sigmaV", sigmaV, "sigmaI", sigmaI, ...
    "RC", RC, "RR", RR, "R0", R0, "kRtrue", kRtrue, ...
    "muC", sum(hC(1:2:end).^2 / RC), ...
    "muR", sum((kRtrue .* hR(2:2:end)).^2 / RR), ...
    "ccmMargin", caseRow.CCM_margin);
end

function est = runEstimator(obs, observationIndex, estimatorIndex, ...
        projectionEnabled, cfg)
switch estimatorIndex
    case 1
        est = runRls(obs, observationIndex, projectionEnabled, cfg);
    case 2
        est = runDualEkf(obs, observationIndex, projectionEnabled, cfg);
    case 3
        est = runLtvJoseph(obs, observationIndex, projectionEnabled, cfg);
    otherwise
        error("pv11:UnknownEstimator", "Unknown estimator index.");
end
end

function est = runRls(obs, observationIndex, projectionEnabled, cfg)
theta = [cfg.Cb / obs.Cinit; obs.Rinit];
P = cfg.rlsP0 * eye(2);
n = numel(obs.hC);
history = zeros(n, 2);
projectionCount = 0;
invalid = 0;
for k = 1:n
    P = P / cfg.rlsLambda;
    if observationIndex == 1
        [theta, P] = rlsMeasurement(theta, P, obs.zMixed(k), ...
            [obs.hC(k), obs.hMixedR(k)], obs.R0);
    elseif mod(k, 2) == 1 && abs(obs.hC(k)) >= 0.012
        [theta, P] = rlsMeasurement(theta, P, obs.zC(k), ...
            [obs.hC(k), 0], obs.RC);
    elseif obs.hR(k) >= 0.12 && obs.ccmMargin >= 0.12
        [theta, P] = rlsMeasurement(theta, P, obs.zR(k), ...
            [0, obs.kRtrue * obs.hR(k)], obs.RR);
    else
        invalid = invalid + 1;
    end
    [theta, activated] = projectTheta(theta, projectionEnabled, cfg);
    projectionCount = projectionCount + activated;
    history(k, :) = theta.';
end
est = finishEstimate(theta, P, history, obs, projectionCount, ...
    invalid, NaN, cfg);
end

function [theta, P] = rlsMeasurement(theta, P, z, H, R)
S = H * P * H.' + R;
K = P * H.' / S;
theta = theta + K * (z - H * theta);
P = (eye(2) - K * H) * P * (eye(2) - K * H).' + K * R * K.';
P = 0.5 * (P + P.');
end

function est = runDualEkf(obs, observationIndex, projectionEnabled, cfg)
v = obs.yTerminal(1) - obs.Rinit * obs.iCap(1);
Pv = 0.25;
theta = [cfg.Cb / obs.Cinit; obs.Rinit];
P = diag([cfg.dualP0Alpha, ...
    (cfg.dualP0RScale * obs.Rtruth(1))^2]);
n = numel(obs.hC);
history = zeros(n, 2);
nis = NaN(n, 1);
projectionCount = 0;
invalid = 0;
for k = 2:n
    vPred = v + obs.qDyn(k - 1) * theta(1) / cfg.Cb;
    PvPred = Pv + 2.5e-5;
    stateR = max(obs.sigmaV^2, 1e-8);
    Kstate = PvPred / (PvPred + stateR);
    yState = obs.yTerminal(k) - theta(2) * obs.iCap(k);
    v = vPred + Kstate * (yState - vPred);
    Pv = (1 - Kstate) * PvPred;
    P = P + cfg.dualQ;
    if observationIndex == 1
        [theta, P, nis(k)] = kalmanMeasurement(theta, P, ...
            obs.zMixed(k), [obs.hC(k), obs.hMixedR(k)], ...
            obs.R0 + 0.15 * Pv, Inf);
    elseif mod(k, 2) == 1 && abs(obs.hC(k)) >= 0.012
        [theta, P, nis(k)] = kalmanMeasurement(theta, P, ...
            obs.zC(k), [obs.hC(k), 0], obs.RC + 0.15 * Pv, Inf);
    elseif obs.hR(k) >= 0.12 && obs.ccmMargin >= 0.12
        [theta, P, nis(k)] = kalmanMeasurement(theta, P, ...
            obs.zR(k), [0, obs.kRtrue * obs.hR(k)], ...
            obs.RR + 0.15 * Pv, Inf);
    else
        invalid = invalid + 1;
    end
    [theta, activated] = projectTheta(theta, projectionEnabled, cfg);
    projectionCount = projectionCount + activated;
    history(k, :) = theta.';
end
history(1, :) = history(2, :);
est = finishEstimate(theta, P, history, obs, projectionCount, ...
    invalid, mean(nis, "omitnan"), cfg);
end

function est = runLtvJoseph(obs, observationIndex, projectionEnabled, cfg)
theta = [cfg.Cb / obs.Cinit; obs.Rinit];
P = diag([cfg.ltvP0Alpha, ...
    (cfg.ltvP0RScale * obs.Rtruth(1))^2]);
n = numel(obs.hC);
history = zeros(n, 2);
nis = NaN(n, 1);
projectionCount = 0;
invalid = 0;
for k = 1:n
    P = P + cfg.ltvQ;
    if observationIndex == 1
        [theta, P, nis(k), accepted] = kalmanMeasurement(theta, P, ...
            obs.zMixed(k), [obs.hC(k), obs.hMixedR(k)], ...
            obs.R0, cfg.nisGate);
    elseif mod(k, 2) == 1 && abs(obs.hC(k)) >= 0.012
        [theta, P, nis(k), accepted] = kalmanMeasurement(theta, P, ...
            obs.zC(k), [obs.hC(k), 0], obs.RC, cfg.nisGate);
    elseif obs.hR(k) >= 0.12 && obs.ccmMargin >= 0.12
        [theta, P, nis(k), accepted] = kalmanMeasurement(theta, P, ...
            obs.zR(k), [0, obs.kRtrue * obs.hR(k)], ...
            obs.RR, cfg.nisGate);
    else
        accepted = false;
    end
    invalid = invalid + ~accepted;
    [theta, activated] = projectTheta(theta, projectionEnabled, cfg);
    projectionCount = projectionCount + activated;
    history(k, :) = theta.';
end
est = finishEstimate(theta, P, history, obs, projectionCount, ...
    invalid, mean(nis, "omitnan"), cfg);
end

function [theta, P, nis, accepted] = kalmanMeasurement(theta, P, z, H, R, gate)
innovation = z - H * theta;
S = H * P * H.' + R;
nis = innovation^2 / max(S, eps);
accepted = isfinite(nis) && nis <= gate;
if accepted
    K = P * H.' / S;
    theta = theta + K * innovation;
    A = eye(2) - K * H;
    P = A * P * A.' + K * R * K.';
    P = 0.5 * (P + P.');
end
end

function [theta, activated] = projectTheta(theta, enabled, cfg)
before = theta;
if enabled
    theta(1) = min(max(theta(1), cfg.Cb / cfg.CBounds(2)), ...
        cfg.Cb / cfg.CBounds(1));
    theta(2) = min(max(theta(2), cfg.RBounds(1)), cfg.RBounds(2));
end
activated = any(abs(theta - before) > 10 * eps(max(abs(before), 1)));
end

function est = finishEstimate(theta, P, history, obs, projectionCount, ...
        invalid, nisMean, cfg)
convergence = convergenceFromHistory(history, obs.alphaTruth, obs.Rtruth);
varC = (cfg.Cb / max(theta(1)^2, eps))^2 * P(1, 1);
est = struct("theta", theta, "P", P, "history", history, ...
    "varC", max(varC, 0), "varR", max(P(2, 2), 0), ...
    "convergence", convergence, ...
    "projectionActivations", projectionCount, ...
    "invalidUpdates", invalid, "nisMean", nisMean);
end

function cycles = convergenceFromHistory(history, alphaTruth, rTruth)
n = size(history, 1);
alphaError = abs(history(:, 1) - alphaTruth(:)) ./ alphaTruth(:);
rError = abs(history(:, 2) - rTruth(:)) ./ rTruth(:);
inside = alphaError <= 0.05 & rError <= 0.05;
window = min(32, n);
starts = conv(double(inside), ones(window, 1), "valid") == window;
first = find(starts, 1, "first");
if isempty(first)
    cycles = n;
else
    cycles = first;
end
end

function summary = summarizeFactorial(rows)
keys = unique(rows(:, ["observation", "estimator", "cell_id"]), ...
    "rows", "stable");
n = height(keys);
N_rows = zeros(n, 1);
C_MAPE_percent = zeros(n, 1);
C_p50_percent = zeros(n, 1);
C_p95_percent = zeros(n, 1);
C_max_percent = zeros(n, 1);
ESR_MAPE_percent = zeros(n, 1);
ESR_p50_percent = zeros(n, 1);
ESR_p95_percent = zeros(n, 1);
ESR_max_percent = zeros(n, 1);
C_bias_percent = zeros(n, 1);
ESR_bias_percent = zeros(n, 1);
empirical_C_variance = zeros(n, 1);
empirical_ESR_variance = zeros(n, 1);
posterior_C_variance = zeros(n, 1);
posterior_ESR_variance = zeros(n, 1);
mean_convergence_cycles = zeros(n, 1);
divergence_rate = zeros(n, 1);
projection_saturation_rate = zeros(n, 1);
mean_invalid_updates = zeros(n, 1);
timing_failure_rate = zeros(n, 1);
NIS_mean = NaN(n, 1);
NEES_mean = zeros(n, 1);
joint_CI_coverage = zeros(n, 1);
for k = 1:n
    mask = rows.observation == keys.observation(k) & ...
        rows.estimator == keys.estimator(k);
    t = rows(mask, :);
    N_rows(k) = height(t);
    C_MAPE_percent(k) = mean(t.C_error_percent);
    C_p50_percent(k) = median(t.C_error_percent);
