    t.fraction_improved), "; ");
end

function value = interaction(summary, metricName)
e3o0 = summary{summary.observation == "O0 Mixed" & ...
    summary.estimator == "E3 LTV/Joseph", metricName};
e3o1 = summary{summary.observation == "O1 Proposed" & ...
    summary.estimator == "E3 LTV/Joseph", metricName};
e1o0 = summary{summary.observation == "O0 Mixed" & ...
    summary.estimator == "E1 RLS", metricName};
e1o1 = summary{summary.observation == "O1 Proposed" & ...
    summary.estimator == "E1 RLS", metricName};
value = (e3o0 - e3o1) - (e1o0 - e1o1);
end

