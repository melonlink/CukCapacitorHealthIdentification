function bootstrap = runPairedBootstrap(rows, cfg)
metricNames = ["C_MAPE", "ESR_MAPE", "C_p95", "ESR_p95", ...
    "timing_failure", "convergence"];
n = numel(cfg.estimators) * numel(metricNames);
estimator = strings(n, 1);
metric = strings(n, 1);
N_pairs = zeros(n, 1);
mean_paired_effect = zeros(n, 1);
median_paired_effect = zeros(n, 1);
ci95_low = zeros(n, 1);
ci95_high = zeros(n, 1);
fraction_improved = zeros(n, 1);
bootstrap_replicates = repmat(cfg.bootstrapReplicates, n, 1);
row = 0;
for iEstimator = 1:numel(cfg.estimators)
    a = rows(rows.estimator == cfg.estimators(iEstimator) & ...
        rows.observation == "O0 Mixed", :);
    b = rows(rows.estimator == cfg.estimators(iEstimator) & ...
        rows.observation == "O1 Proposed", :);
    a = sortrows(a, ["case_id", "noise_profile", "skew_ns", "seed"]);
    b = sortrows(b, ["case_id", "noise_profile", "skew_ns", "seed"]);
    assert(isequal(a(:, ["case_id", "noise_profile", "skew_ns", "seed"]), ...
        b(:, ["case_id", "noise_profile", "skew_ns", "seed"])), ...
        "pv11:UnpairedFactorial");
    for iMetric = 1:numel(metricNames)
        row = row + 1;
        [x0, x1, mode] = metricVectors(a, b, metricNames(iMetric));
        stats = pairedBootstrap(x0, x1, mode, ...
            cfg.bootstrapReplicates, 43100 + 100 * iEstimator + iMetric);
        estimator(row) = cfg.estimators(iEstimator);
        metric(row) = metricNames(iMetric);
        N_pairs(row) = numel(x0);
        mean_paired_effect(row) = stats.meanEffect;
        median_paired_effect(row) = stats.medianEffect;
        ci95_low(row) = stats.ci(1);
        ci95_high(row) = stats.ci(2);
        fraction_improved(row) = stats.fractionImproved;
    end
end
bootstrap = table(estimator, metric, N_pairs, mean_paired_effect, ...
    median_paired_effect, ci95_low, ci95_high, fraction_improved, ...
    bootstrap_replicates);
end

function [x0, x1, mode] = metricVectors(a, b, metric)
switch metric
    case {"C_MAPE", "C_p95"}
        x0 = a.C_error_percent;
        x1 = b.C_error_percent;
    case {"ESR_MAPE", "ESR_p95"}
        x0 = a.ESR_error_percent;
        x1 = b.ESR_error_percent;
    case "timing_failure"
        x0 = double(a.timing_failure);
        x1 = double(b.timing_failure);
    case "convergence"
        x0 = a.convergence_cycles;
        x1 = b.convergence_cycles;
end
if endsWith(metric, "p95")
    mode = "p95";
else
    mode = "mean";
end
end

function stats = pairedBootstrap(x0, x1, mode, nBoot, seed)
rng(seed, "twister");
d = x0 - x1;
n = numel(d);
boot = zeros(nBoot, 1);
batchSize = 250;
for first = 1:batchSize:nBoot
    last = min(first + batchSize - 1, nBoot);
    indices = randi(n, n, last - first + 1);
    if mode == "p95"
        boot(first:last) = (prctile(x0(indices), 95, 1) - ...
            prctile(x1(indices), 95, 1)).';
    else
        boot(first:last) = mean(d(indices), 1).';
    end
end
if mode == "p95"
    effect = prctile(x0, 95) - prctile(x1, 95);
else
    effect = mean(d);
end
stats = struct("meanEffect", effect, "medianEffect", median(d), ...
    "ci", prctile(boot, [2.5, 97.5]), ...
    "fractionImproved", mean(d > 0));
end

