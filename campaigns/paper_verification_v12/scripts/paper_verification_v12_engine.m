function obs = simulateDynamicObservation(scenario, seed, cfg)
rng(seed, "twister");
n = cfg.dynamicCycles;
k = (1:n).';
phase = 2 * pi * k / 37;
loadFactor = 0.75 * ones(n, 1);
Ctruth = cfg.Cb * ones(n, 1);
Rtruth = cfg.Rb * ones(n, 1);
switch scenario
    case "load_25_to_75"
        loadFactor(1:(cfg.dynamicStepCycle - 1)) = 0.25;
        loadFactor(cfg.dynamicStepCycle:end) = 0.75;
    case "C_1_to_0p8"
        Ctruth(cfg.dynamicStepCycle:end) = 0.8 * cfg.Cb;
    case "ESR_1_to_2"
        Rtruth(cfg.dynamicStepCycle:end) = 2 * cfg.Rb;
end
alphaTruth = cfg.Cb ./ Ctruth;
currentScale = 2.45 .* loadFactor;
iSum = max(currentScale .* (1 + 0.13 * sin(phase)), 0.12);
hC = max(abs(sqrt(loadFactor) .* 0.052 .* ...
    (1 + 0.38 * sin(phase + 0.3))), 0.012);
hMixedR = 0.62 .* iSum .* sin(phase + 0.9);
sigmaV = 2.2e-3;
sigmaI = 1.2e-3;
commonNoise = sigmaV * randn(n, 1);
nC = 0.72 * commonNoise + 0.70 * sigmaV * randn(n, 1);
nR = 0.54 * commonNoise + 0.84 * sigmaV * randn(n, 1);
kRtrue = cfg.kRCalibration;
rawSkew = 8e4 .* (0.65 + 0.35 * sin(phase + 0.7)) .* 135e-9;
residualSkew = 8e4 .* sin(phase + 0.7) .* 50e-9;
zC = hC .* alphaTruth + 0.002 .* hC .* sin(2 * phase) + nC;
zR = kRtrue .* iSum .* Rtruth + residualSkew + nR;
zMixed = hC .* alphaTruth + hMixedR .* Rtruth + ...
    0.55 .* nC + 0.45 .* nR + 0.62 .* rawSkew;
qDyn = cfg.Cb .* (0.010 + 0.023 * sin(phase));
iCap = currentScale .* sign(sin(phase + 0.1)) .* 0.8;
vIdeal = zeros(n, 1);
vIdeal(1) = 36;
for j = 2:n
    vIdeal(j) = vIdeal(j - 1) + qDyn(j - 1) / Ctruth(j - 1);
end
yTerminal = vIdeal + Rtruth .* iCap + sigmaV .* randn(n, 1);
RC = max(2 * sigmaV^2, 1e-8);
RR = max(2 * sigmaV^2 + (sigmaI * max(Rtruth))^2, 1e-8);
obs = struct("hC", hC, "hR", iSum, "hMixedR", hMixedR, ...
    "zC", zC, "zR", zR, "zMixed", zMixed, "qDyn", qDyn, ...
    "iCap", iCap, "yTerminal", yTerminal, "Ctruth", Ctruth, ...
    "Rtruth", Rtruth, "alphaTruth", alphaTruth, ...
    "Cinit", 1.15 * cfg.Cb, "Rinit", 0.70 * cfg.Rb, ...
    "sigmaV", sigmaV, "sigmaI", sigmaI, "RC", RC, "RR", RR, ...
    "R0", RC + RR, "kRtrue", kRtrue, ...
    "muC", sum(hC(1:2:end).^2 / RC), ...
    "muR", sum((kRtrue .* iSum(2:2:end)).^2 / RR), ...
    "ccmMargin", min(loadFactor));
end

function cycles = dynamicConvergence(history, obs, stepCycle)
alphaError = abs(history(:, 1) - obs.alphaTruth) ./ obs.alphaTruth;
rError = abs(history(:, 2) - obs.Rtruth) ./ obs.Rtruth;
inside = alphaError <= 0.05 & rError <= 0.05;
window = 16;
starts = conv(double(inside(stepCycle:end)), ones(window, 1), ...
    "valid") == window;
first = find(starts, 1, "first");
if isempty(first)
    cycles = numel(inside) - stepCycle + 1;
else
    cycles = first - 1;
end
end

function value = crossCoupling(scenario, Cest, Rest, obs, cfg)
post = cfg.dynamicStepCycle:numel(Cest);
switch scenario
    case "C_1_to_0p8"
        value = max(100 * abs(Rest(post) ./ obs.Rtruth(post) - 1));
    case "ESR_1_to_2"
        value = max(100 * abs(Cest(post) ./ obs.Ctruth(post) - 1));
    otherwise
        value = max([100 * abs(Cest(post) ./ obs.Ctruth(post) - 1); ...
            100 * abs(Rest(post) ./ obs.Rtruth(post) - 1)]);
end
end

function pe = computePhysicalPeBounds(cfg)
source = load(cfg.modelBSource, "traces");
traces = source.traces;
n = numel(traces);
case_id = "MB-" + compose("%03d", (1:n).');
duty = zeros(n, 1);
load_fraction = zeros(n, 1);
I_C_min = zeros(n, 1);
I_sum_min = zeros(n, 1);
T_w_min = repmat(cfg.safeWindowS, n, 1);
kR_min = repmat(cfg.kRCalibrationGuard * ...
    cfg.lockedV21.edgeGainCorrection, n, 1);
R_C_max = repmat(cfg.maxRC, n, 1);
R_R_max = repmat(cfg.maxRR, n, 1);
mu_C_lower = zeros(n, 1);
mu_C_empirical = zeros(n, 1);
mu_R_lower = zeros(n, 1);
mu_R_empirical = zeros(n, 1);
ratio_C = zeros(n, 1);
ratio_R = zeros(n, 1);
sign_invariant = false(n, 1);
for j = 1:n
    trace = traces{j};
    b = trace.traceB;
    safe = b.tau >= cfg.safeGuardS & ...
        b.tau <= cfg.safeGuardS + cfg.safeWindowS;
    t = b.tau(safe);
    iC = b.iC(safe);
    iSum = b.i1(safe) + b.i2(safe);
    duty(j) = trace.p.D;
    load_fraction(j) = trace.actualLoad;
    I_C_min(j) = min(abs(iC));
    I_sum_min(j) = min(iSum);
    sign_invariant(j) = all(iC >= 0) || all(iC <= 0);
    qEmpirical = abs(trapz(t, iC));
    mu_C_lower(j) = (I_C_min(j) * T_w_min(j) / ...
        cfg.Cb)^2 / R_C_max(j);
    mu_C_empirical(j) = (qEmpirical / cfg.Cb)^2 / R_C_max(j);
    mu_R_lower(j) = (kR_min(j) * I_sum_min(j))^2 / R_R_max(j);
    mu_R_empirical(j) = mean((kR_min(j) .* iSum).^2 / R_R_max(j));
    ratio_C(j) = mu_C_empirical(j) / mu_C_lower(j);
    ratio_R(j) = mu_R_empirical(j) / mu_R_lower(j);
end
pe = table(case_id, duty, load_fraction, I_C_min, I_sum_min, ...
    T_w_min, kR_min, R_C_max, R_R_max, mu_C_lower, ...
    mu_C_empirical, mu_R_lower, mu_R_empirical, ratio_C, ...
    ratio_R, sign_invariant);
assert(all(pe.ratio_C >= 1 - 1e-10) && all(pe.ratio_R >= 1 - 1e-10), ...
    "pv11:PeLowerBoundViolation");
assert(all(pe.sign_invariant), "pv11:SafeWindowSignChange");
end

