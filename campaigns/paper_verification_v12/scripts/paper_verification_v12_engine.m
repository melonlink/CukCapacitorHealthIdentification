    P_envelope, VariableNames=["scenario", "direction", "window", ...
    "P_KF", "P_envelope"]);
assert(all(tableOut.bound_pass), "pv11:CovarianceEnvelopeViolation");
end

function value = covarianceFixedPoint(qn, mu)
if qn == 0
    value = 0;
else
    value = (-qn + sqrt(qn^2 + 4 * qn / mu)) / 2;
end
end

function [pKf, pEnvelope] = covarianceSequences(p0, qn, ...
        muEmpirical, muLower, n)
pKf = zeros(n, 1);
pEnvelope = zeros(n, 1);
pKf(1) = p0;
pEnvelope(1) = p0;
for k = 2:n
    pKf(k) = 1 / (1 / (pKf(k - 1) + qn) + muEmpirical);
    pEnvelope(k) = (pEnvelope(k - 1) + qn) / ...
        (1 + muLower * (pEnvelope(k - 1) + qn));
end
end

function variance = scalarCovarianceMonteCarlo(p0, qn, mu, nSeeds, seed)
rng(seed, "twister");
nWindow = 200;
errors = zeros(nSeeds, 1);
h = sqrt(mu);
R = 1;
for iSeed = 1:nSeeds
    truth = 0;
    estimate = sqrt(p0) * randn;
    p = p0;
    for k = 1:nWindow
        truth = truth + sqrt(qn) * randn;
        p = p + qn;
        measurement = h * truth + randn;
        gain = p * h / (h^2 * p + R);
        estimate = estimate + gain * (measurement - h * estimate);
        p = (1 - gain * h)^2 * p + gain^2 * R;
    end
    errors(iSeed) = estimate - truth;
end
variance = var(errors, 0);
end

