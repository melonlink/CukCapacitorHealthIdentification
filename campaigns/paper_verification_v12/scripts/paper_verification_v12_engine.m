function decisions = decideResults(summary, bootstrap, dynamic, pe, ...
        covariance, projection, cfg)
obsC = bootstrap(bootstrap.metric == "C_MAPE", :);
obsR = bootstrap(bootstrap.metric == "ESR_MAPE", :);
obsConvergence = bootstrap(bootstrap.metric == "convergence", :);
observationBroadValue = all(obsC.mean_paired_effect > 0) && ...
    nnz(obsR.mean_paired_effect > 0) >= 2 && ...
    all(obsConvergence.mean_paired_effect > 0);
e3 = summary(summary.estimator == "E3 LTV/Joseph" & ...
    summary.observation == "O1 Proposed", :);
e1 = summary(summary.estimator == "E1 RLS" & ...
    summary.observation == "O1 Proposed", :);
e2 = summary(summary.estimator == "E2 Dual EKF" & ...
    summary.observation == "O1 Proposed", :);
e3AdvantageCount = ...
    double(e3.C_MAPE_percent < min([e1.C_MAPE_percent, ...
        e2.C_MAPE_percent])) + ...
    double(e3.ESR_MAPE_percent < min([e1.ESR_MAPE_percent, ...
        e2.ESR_MAPE_percent])) + ...
    double(e3.mean_convergence_cycles < ...
        min([e1.mean_convergence_cycles, e2.mean_convergence_cycles])) + ...
    double(e3.timing_failure_rate < ...
        min([e1.timing_failure_rate, e2.timing_failure_rate])) + ...
    double(abs(e3.joint_CI_coverage - 0.95) < ...
        min(abs([e1.joint_CI_coverage, e2.joint_CI_coverage] - 0.95)));
structuredExtra = e3AdvantageCount >= 2;
if observationBroadValue && structuredExtra
    factorialDecision = "OBSERVATION_AND_ESTIMATOR_HAVE_COMPLEMENTARY_VALUE";
    primaryInnovation = "CO-DESIGN";
elseif observationBroadValue
    factorialDecision = "OBSERVATION_FRAMEWORK_IS_PRIMARY_INNOVATION";
    primaryInnovation = "OBSERVATION";
elseif structuredExtra
    factorialDecision = "ESTIMATOR_IS_PRIMARY_INNOVATION";
    primaryInnovation = "ESTIMATOR";
else
    factorialDecision = "STRUCTURAL_NOVELTY_WEAKENED";
    primaryInnovation = "OBSERVATION";
end
pePass = all(pe.ratio_C >= 1) && all(pe.ratio_R >= 1);
covariancePass = all(covariance.bound_pass) && ...
    projection.divergence_rate(projection.projection_state == "OFF") == 0;
e3Dynamic = dynamic(dynamic.observation == "O1 Proposed" & ...
    dynamic.estimator == "E3 LTV/Joseph", :);
stepRows = e3Dynamic(ismember(e3Dynamic.scenario, ...
    ["C_1_to_0p8", "ESR_1_to_2"]), :);
dynamicPass = all(~dynamic.divergence_flag) && ...
    all(stepRows.convergence_cycles < ...
        cfg.dynamicCycles - cfg.dynamicStepCycle + 1) && ...
    all(stepRows.C_tracking_MAPE_percent <= 5) && ...
    all(stepRows.ESR_tracking_MAPE_percent <= 5);
if factorialDecision == "STRUCTURAL_NOVELTY_WEAKENED"
    freezeDecision = "OBSERVATION_NOVELTY_WEAK";
elseif ~covariancePass
    freezeDecision = "COVARIANCE_THEORY_NOT_SUPPORTED";
elseif ~dynamicPass
    freezeDecision = "REOPEN_ALGORITHM";
elseif pePass
    freezeDecision = "FREEZE_FOR_MANUSCRIPT";
else
    freezeDecision = "FREEZE_WITH_THEORY_CAVEAT";
end
decisions = struct("factorialDecision", factorialDecision, ...
    "primaryInnovation", primaryInnovation, ...
    "freezeDecision", freezeDecision, "pePass", pePass, ...
    "covariancePass", covariancePass, "dynamicPass", dynamicPass, ...
    "e3AdvantageCount", e3AdvantageCount);
end

