function summary = paper_verification_v12_engine(packageRoot)
%PAPER_VERIFICATION_V12_ENGINE Recalibrated Paper Verification v1.2 package.
% The frozen Paper Verification v1 cases and Model-B anchors are reused.
% No frozen TS-SLTVKE implementation file is modified.

arguments
    packageRoot (1, 1) string
end

cfg = makeConfiguration(packageRoot);
folders = [cfg.rawDir, cfg.tableDir, cfg.figureDir, cfg.logDir, ...
    fullfile(packageRoot, "baselines")];
ensureFolders(folders);

cases = readtable(cfg.caseSource, TextType="string");
assert(height(cases) == 48, "pv11:BlindCaseCount", ...
    "The frozen Paper Verification v1 blind set must contain 48 cases.");
locked = load(cfg.covarianceSource, "locked");
cfg.lockedV21 = locked.locked;

writeLockedHyperparameters(cfg);
writeFactorialProtocol(packageRoot, cfg);

fprintf("Paper Verification v1.2: running 2x3 factorial (%d rows) ...\n", ...
    height(cases) * numel(cfg.noiseNames) * numel(cfg.skewNs) * 6);
[factorial, obsCache] = runFactorial(cases, cfg);
writetable(factorial, fullfile(cfg.rawDir, "factorial_rows.csv"));
factorialSummary = summarizeFactorial(factorial);
writetable(factorialSummary, ...
    fullfile(cfg.tableDir, "table_observation_estimator_factorial.csv"));

fprintf("Paper Verification v1.2: paired bootstrap (%d replicates) ...\n", ...
    cfg.bootstrapReplicates);
bootstrap = runPairedBootstrap(factorial, cfg);
writetable(bootstrap, ...
    fullfile(cfg.tableDir, "table_observation_effect_bootstrap.csv"));

fprintf("Paper Verification v1.2: dynamic factorial ...\n");
[dynamic, dynamicHistory] = runDynamicFactorial(cfg);
writetable(dynamic, fullfile(cfg.tableDir, "table_factorial_dynamic.csv"));

fprintf("Paper Verification v1.2: physical PE lower bounds ...\n");
pe = computePhysicalPeBounds(cfg);
writetable(pe, fullfile(cfg.tableDir, "table_physical_PE_lower_bound.csv"));

fprintf("Paper Verification v1.2: covariance envelopes ...\n");
[covariance, covarianceHistory] = validateCovarianceBounds(pe, cfg);
writetable(covariance, ...
    fullfile(cfg.tableDir, "table_covariance_bound_validation.csv"));

fprintf("Paper Verification v1.2: projection ON/OFF (%d seeds) ...\n", ...
    cfg.projectionSeeds);
projection = runProjectionCheck(cfg);
writetable(projection, fullfile(cfg.tableDir, "table_projection_on_off.csv"));

decisions = decideResults(factorialSummary, bootstrap, dynamic, pe, ...
    covariance, projection, cfg);
claims = makeFinalClaims(decisions, factorialSummary, pe, covariance, ...
    projection);
writetable(claims, fullfile(cfg.tableDir, ...
    "table_paper_final_claims_v12.csv"));

metrics = makeResultMetrics(decisions, factorial, factorialSummary, ...
    bootstrap, dynamic, pe, covariance, projection);
writetable(metrics, fullfile(packageRoot, ...
    "result_metrics_paper_v12.csv"));

makeFigures(factorial, factorialSummary, bootstrap, dynamic, ...
    dynamicHistory, pe, covarianceHistory, projection, cfg);
writeReports(packageRoot, decisions, factorialSummary, bootstrap, ...
    dynamic, pe, covariance, projection, cfg);

summary = struct( ...
    "factorialRows", height(factorial), ...
    "factorialCells", height(factorialSummary), ...
    "bootstrapReplicates", cfg.bootstrapReplicates, ...
    "peCases", height(pe), ...
    "projectionSeeds", cfg.projectionSeeds, ...
    "factorialDecision", decisions.factorialDecision, ...
    "primaryInnovation", decisions.primaryInnovation, ...
    "freezeDecision", decisions.freezeDecision);
save(fullfile(cfg.rawDir, "paper_verification_v12_workspace.mat"), ...
    "cfg", "cases", "factorial", "factorialSummary", "bootstrap", ...
    "dynamic", "dynamicHistory", "pe", "covariance", ...
    "covarianceHistory", "projection", "decisions", "claims", ...
    "metrics", "obsCache", "summary");
fprintf("Paper Verification v1.2 generated: %s / %s.\n", ...
    decisions.primaryInnovation, decisions.freezeDecision);
end

