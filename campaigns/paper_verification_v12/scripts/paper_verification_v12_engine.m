        historyScenario(hIdx) = scenarioNames(iScenario);
        historyDirection(hIdx) = directions(iDirection);
        window(hIdx) = (0:199).';
        P_KF(hIdx) = pKf;
        P_envelope(hIdx) = pEnvelope;
    end
