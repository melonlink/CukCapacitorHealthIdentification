function metrics=generate_result_metrics_v21(v21Root)
%GENERATE_RESULT_METRICS_V21 Assemble compact audit rows from full tables.

if nargin<1, v21Root=fileparts(fileparts(mfilename("fullpath"))); end
tableDir=fullfile(v21Root,"results","tables");
joint=readtable(fullfile(tableDir,"table_adc_afe_joint_v21.csv"),"TextType","string");
geometry=readtable(fullfile(tableDir,"table_sampling_geometry_v21.csv"),"TextType","string");
edge=readtable(fullfile(tableDir,"table_edge_bias_variance_v21.csv"),"TextType","string");
stats=readtable(fullfile(tableDir,"table_NIS_NEES_v21.csv"),"TextType","string");
features=readtable(fullfile(tableDir,"table_modelB_edge_features_v21.csv"),"TextType","string");
comparison=readtable(fullfile(tableDir,"table_modelAP_vs_B_v21.csv"),"TextType","string");
crlb=readtable(fullfile(tableDir,"table_CRLB_v21.csv"),"TextType","string");
rates=[.8e6,1.6e6,5e6]; labels=["rejected_v2_like","minimum_candidate","recommended_bench"];
rows=cell(3,47); nominalStats=stats(stats.scenario=="nominal",:);
feature=features(features.ESL_nH==20 & abs(features.D-.4)<1e-12 & ...
    features.actual_load_fraction==1,:);
comp=comparison(comparison.ESL_nH==20 & abs(comparison.D-.4)<1e-12 & ...
    comparison.load_fraction==1,:);
for k=1:3
    rate=rates(k); q=joint(joint.fs_adc_Hz==rate & joint.adc_bits==16 & ...
        joint.afe_order==2 & joint.afe_fc_v_Hz==2e6 & ...
        joint.afe_fc_i1_Hz==1e6 & abs(joint.sample_phase-.13)<1e-12 & ...
        joint.perturbation=="nominal_fsw",:);
    g=geometry(abs(geometry.D-.4)<1e-12 & geometry.guard_us==.5 & ...
        geometry.points_required_per_side==3 & geometry.window_us==2 & ...
        geometry.fs_adc_Hz==rate,:);
    e=edge(edge.fs_adc_Hz==rate & edge.edge_guard_us==.5 & ...
        edge.edge_window_us==2 & edge.edge_points_per_side==3,:);
    if isempty(e), ev=nan_edge(); else, ev=e(1,:); end
    if rate==1.6e6
        f=crlb(crlb.sensitivity_dimension=="adc" & crlb.level=="1.6M",:);
    elseif rate==5e6
        f=crlb(crlb.sensitivity_dimension=="adc" & crlb.level=="5M",:);
    else
        f=crlb(crlb.sensitivity_dimension=="timing" & crlb.level=="0ns",:);
    end
    status="PASS"; if ~q.accuracy_geometry_pass, status="FAIL"; end
    rows(k,:)={labels(k),rate,1/rate,16,.13,2,q.window_actual_us, ...
        q.points_available_pre,q.points_available_post,q.sampling_geometry_feasible, ...
        g.duty_on_margin_us,g.duty_off_margin_us,2,2e6,1e6,1e6,q.alias_ratio_dB, ...
        scalar(ev,"edge_predicted_variance_Ohm2"), ...
        scalar(ev,"edge_empirical_variance_Ohm2"), ...
        scalar(ev,"esr_predicted_sigma_Ohm"),scalar(ev,"esr_empirical_sigma_Ohm"), ...
        f.C_information,f.ESR_information,"conditional_structured",false, ...
        "disjoint",false,q.NIS_V_mean,q.NIS_C_mean,q.NIS_R_mean, ...
        nominalStats.NEES_full_mean,nominalStats.NEES_param_mean, ...
        nominalStats.CI_C_95_coverage>=.95,nominalStats.CI_ESR_95_coverage>=.95, ...
        "Simscape_Model_B",feature.ring_freq_Hz,feature.ring_zeta, ...
        feature.ring_overshoot_V,feature.ring_settle_s,comp.modelB_waveform_NRMSE, ...
        f.CRLB_C,f.CRLB_ESR,f.rmse_to_crlb_C,f.rmse_to_crlb_ESR, ...
        q.C_MAPE_percent,q.ESR_MAPE_percent,status};
end
names=["configuration","fs_adc_Hz","adc_interval_s","adc_bits", ...
    "sample_phase","window_requested_us","window_actual_us", ...
    "points_available_pre","points_available_post","sampling_geometry_feasible", ...
    "duty_on_margin_us","duty_off_margin_us","afe_order","afe_fc_v_Hz", ...
    "afe_fc_i1_Hz","afe_fc_i2_Hz","alias_ratio_dB", ...
    "edge_predicted_variance_V2","edge_empirical_variance_V2", ...
    "esr_predicted_sigma_Ohm","esr_empirical_sigma_Ohm","C_information", ...
    "ESR_information","estimator_variant","gain_mask_used","data_policy", ...
    "double_counting_flag","NIS_V","NIS_C","NIS_R","NEES_full", ...
    "NEES_param","CI_C_contains_true","CI_ESR_contains_true", ...
    "parasitic_model","ring_freq_Hz","ring_zeta","ring_overshoot_V", ...
    "ring_settle_s","modelB_waveform_NRMSE","CRLB_C","CRLB_ESR", ...
    "rmse_to_crlb_C","rmse_to_crlb_ESR","C_MAPE_percent", ...
    "ESR_MAPE_percent","status"];
metrics=cell2table(rows,"VariableNames",names);
writetable(metrics,fullfile(tableDir,"result_metrics_v21.csv"));
writetable(metrics,fullfile(v21Root,"result_metrics_v21.csv"));
fprintf("v2.1 result metrics: %d compact configurations written.\n",height(metrics));
end

function e=nan_edge()
e=table(NaN,NaN,NaN,NaN,VariableNames=["edge_predicted_variance_Ohm2", ...
    "edge_empirical_variance_Ohm2","esr_predicted_sigma_Ohm", ...
    "esr_empirical_sigma_Ohm"]);
end

function value=scalar(t,name)
if ismember(name,t.Properties.VariableNames), value=t.(name)(1); else, value=NaN; end
end
