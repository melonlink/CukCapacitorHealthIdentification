    "table_algorithm_final_selection.csv"),TextType="string");
algNew = readtable(fullfile(algNewRoot,"results","tables", ...
    "table_algorithm_final_selection.csv"),TextType="string");
[algOld,algNew] = alignTables(algOld,algNew,"metric",height(algOld));
assert(all(algOld.final_decision == algNew.final_decision), ...
    "krRerun:DecisionChanged","Final decision token changed.");
algorithmMetricDelta = metricLongTable(algOld,algNew);

staticOld = readAlgorithmTable(algOldRoot, ...
    "table_algorithm_static_comparison.csv");
staticNew = readAlgorithmTable(algNewRoot, ...
    "table_algorithm_static_comparison.csv");
[staticOld,staticNew] = alignTables(staticOld,staticNew, ...
    ["method" "mode"],6);

noiseOld = readAlgorithmTable(algOldRoot, ...
    "table_algorithm_noise_timing.csv");
noiseNew = readAlgorithmTable(algNewRoot, ...
    "table_algorithm_noise_timing.csv");
[noiseOld,noiseNew] = alignTables(noiseOld,noiseNew, ...
    ["method" "mode" "noise_profile" "skew_ns"],48);

abruptOld = readAlgorithmTable(algOldRoot, ...
    "table_algorithm_abrupt_step.csv");
abruptNew = readAlgorithmTable(algNewRoot, ...
    "table_algorithm_abrupt_step.csv");
[abruptOld,abruptNew] = alignTables(abruptOld,abruptNew, ...
    ["method" "mode" "case_id"],18);

rampOld = readAlgorithmTable(algOldRoot, ...
    "table_algorithm_ramp_tracking.csv");
