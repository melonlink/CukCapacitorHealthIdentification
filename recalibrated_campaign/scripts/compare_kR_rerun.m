    ["observation" "estimator"],6);
pvSummaryDelta = compareNumericVariables(pvOld,pvNew, ...
    "PV_FACTORIAL_SUMMARY");

effectOld = readtable(fullfile(pvOldRoot,"results","tables", ...
    "table_observation_effect_bootstrap.csv"),TextType="string");
effectNew = readtable(fullfile(pvNewRoot,"results","tables", ...
    "table_observation_effect_bootstrap.csv"),TextType="string");
[effectOld,effectNew] = alignTables(effectOld,effectNew, ...
    ["estimator" "metric"],18);
effectDelta = compareNumericVariables(effectOld,effectNew, ...
    "PV_OBSERVATION_BOOTSTRAP");

peOld = readtable(fullfile(pvOldRoot,"results","tables", ...
    "table_physical_PE_lower_bound.csv"),TextType="string");
peNew = readtable(fullfile(pvNewRoot,"results","tables", ...
    "table_physical_PE_lower_bound.csv"),TextType="string");
