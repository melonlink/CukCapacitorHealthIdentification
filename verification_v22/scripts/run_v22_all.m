function T = build_code_utilization(cfg, budget)
n = height(budget) * numel(cfg.profiles) * numel(cfg.architectures);
rows = cell(n, 20);
row = 0;
for a = 1:numel(cfg.architectures)
    arch = cfg.architectures(a);
    for p = 1:numel(cfg.profiles)
        profile = cfg.profiles(p);
        rLsb = (arch.rHighV - arch.rLowV) / (2^profile.bits - 1);
        cLsb = (arch.cHighV - arch.cLowV) / (2^profile.bits - 1);
        rmsNoiseCodes = 2^(profile.bits - profile.enob) / sqrt(12);
        for k = 1:height(budget)
            rCodes = budget.edge_ESR_signal_mV(k) * 1e-3 / rLsb;
            cCodes = budget.charge_C_signal_mV(k) * 1e-3 / cLsb;
            row = row + 1;
            rows(row, :) = {arch.id, arch.name, profile.name, profile.bits, ...
                profile.enob, profile.fsHz, budget.operating_case(k), ...
                budget.C(k), budget.ESR(k), rLsb, cLsb, rCodes, cCodes, ...
                rmsNoiseCodes, risk_label(rCodes), risk_label(cCodes), ...
                arch.rHighV - arch.rLowV, arch.cHighV - arch.cLowV, ...
                budget.vT_baseline_V(k), arch.separateEdgeChannel};
        end
    end
end
names = ["voltage_architecture" "architecture_name" "ADC_mode" ...
    "nominal_bits" "ENOB" "fs_adc_Hz" "operating_case" "C_F" ...
    "ESR_Ohm" "LSB_edge_plant_V" "LSB_C_plant_V" "ESR_edge_codes" ...
    "C_charge_window_codes" "RMS_noise_codes" "ESR_code_risk" ...
    "C_code_risk" "edge_plant_span_V" "C_plant_span_V" ...
    "vT_baseline_V" "separate_edge_channel"];
T = cell2table(rows, VariableNames=names);
end

function label = risk_label(codes)
if codes < 4
    label = "HIGH_RISK_LT4";
elseif codes < 16
    label = "QUANTIZATION_SENSITIVE_4_TO_16";
else
    label = "CANDIDATE_GE16";
end
end

function T = build_kr_table(cfg)
duties = [.3 .4 .55 .65];
loads = ["low_CCM" "nominal" "high"];
loadScale = [.5 1 2];
tolerances = [-.05 -.01 .01 .05];
n = numel(duties) * numel(loads) * numel(cfg.CFactors) * ...
    numel(cfg.ESRFactors) * numel(cfg.architectures) * numel(tolerances);
rows = cell(n, 14);
row = 0;
dynamicScale = [1.5 .5 1.0];
for a = 1:numel(cfg.architectures)
    arch = cfg.architectures(a);
    for D = duties
        for l = 1:numel(loads)
            for cFactor = cfg.CFactors
                for rFactor = cfg.ESRFactors
                    dynamic = dynamicScale(a) * (.008 * (D - .475) / .175 + ...
                        .004 * (loadScale(l) - 1) + .003 * (rFactor - 1) + ...
                        .002 * (cFactor - .9) / .1);
                    for tolerance = tolerances
                        raw = arch.nominalKR * (1 + tolerance + dynamic);
                        onceCal = raw / (arch.nominalKR * (1 + tolerance));
                        row = row + 1;
                        rows(row, :) = {arch.id, D, loads(l), loadScale(l), ...
                            cfg.C0 * cFactor, cfg.ESR0 * rFactor, tolerance, ...
                            arch.highpassHz, arch.lowpassHz, raw, onceCal, ...
                            100 * (raw - 1), 100 * (onceCal - 1), ...
                            abs(onceCal - 1) < .01};
                    end
                end
            end
        end
    end
end
names = ["voltage_architecture" "D" "load" "load_scale" "C_F" ...
    "ESR_Ohm" "AFE_component_tolerance" "AFE_highpass_Hz" ...
    "AFE_lowpass_Hz" "kR_raw" "kR_after_once_calibration" ...
    "raw_deviation_percent" "calibrated_deviation_percent" ...
    "one_time_calibration_within_1_percent"];
T = cell2table(rows, VariableNames=names);
end

function signal = select_worst_signal(cfg, budget, baseline, arch)
[~, idx] = min(normalize01(budget.edge_ESR_signal_mV) + ...
    normalize01(budget.charge_C_signal_mV));
signal = make_signal(cfg, budget(idx, :), baseline, arch);
end

function y = normalize01(x)
span = max(x) - min(x);
y = (x - min(x)) / max(span, eps);
end

function signal = make_signal(cfg, row, baseline, arch)
b = baseline(baseline.operating_case == row.operating_case, :);
cFactor = row.C / cfg.C0;
rFactor = row.ESR / cfg.ESR0;
loadTerm = load_term(row.load);
dynamicScale = [1.5 .5 1.0];
a = find(string({cfg.architectures.id}) == arch.id, 1);
dynamic = dynamicScale(a) * (.008 * (row.D - .475) / .175 + ...
    .004 * loadTerm + .003 * (rFactor - 1) + ...
    .002 * (cFactor - .9) / .1);
signal = struct("C", row.C, "ESR", row.ESR, "i1", row.i1, ...
    "i2", row.i2, "I_sum", row.I_sum, "Q", row.Q_safe_C, ...
    "zC", row.charge_C_signal_mV * 1e-3, ...
    "zR", row.edge_ESR_signal_mV * 1e-3, ...
    "vBase", row.vT_baseline_V, ...
    "edgeSlopeVPerS", b.edge_slope_V_per_s, ...
    "kRTrue", arch.nominalKR * (1 + .01 + dynamic));
end

function value = load_term(label)
if label == "low_CCM"
    value = -.5;
elseif label == "high" || label == "high_D"
    value = 1;
else
    value = 0;
end
end

