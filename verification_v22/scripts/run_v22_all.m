    profile.fsHz, noise, cal.name, true, cal.offsetResidualLsb, ...
    cal.gainResidualFraction, profile.inlLsb, profile.dnlLsb, .25, ...
    cal.timingResidualNs, 5, ...
    cal.settlingResidualFraction, 5000, 150, ...
    "DATASHEET_NOT_SPECIFIED_PARAMETER_SWEEP", m.C_MAPE_percent, ...
    m.ESR_MAPE_percent, m.C_bias_percent, m.ESR_bias_percent, ...
    m.NIS_C_mean, m.NIS_R_mean, m.NEES_mean, m.CI_C_95_coverage, ...
    m.CI_ESR_95_coverage, m.accuracy_pass, m.confidence_pass};
