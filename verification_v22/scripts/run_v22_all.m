function summary = run_v22_all(v22Root)
%RUN_V22_ALL Execute the complete native-DSP-ADC feasibility study.

if nargin < 1
    v22Root = fileparts(fileparts(mfilename("fullpath")));
end
repoRoot = fileparts(v22Root);
addpath(genpath(fullfile(repoRoot, "cuk_cap_health_verification")), ...
    genpath(fullfile(repoRoot, "verification_v2")), ...
    genpath(fullfile(repoRoot, "verification_v21")), ...
    genpath(v22Root));
create_folders(v22Root);
cfg = v22_default_config();
tableDir = fullfile(v22Root, "results", "tables");
rawDir = fullfile(v22Root, "results", "raw");

profileTable = build_profile_table(cfg);
writetable(profileTable, fullfile(tableDir, ...
    "table_target_dsp_adc_profile_v22.csv"));
[baselineTable, budgetTable, currentRangeTable, bases] = ...
    v22_modelb_baselines(v22Root, cfg);
geometryTable = v22_sampling_geometry(v22Root, cfg, baselineTable, bases);
codeTable = build_code_utilization(cfg, budgetTable);
writetable(codeTable, fullfile(tableDir, ...
    "table_adc_code_utilization_v22.csv"));
kRTable = build_kr_table(cfg);
writetable(kRTable, fullfile(tableDir, "table_kR_robustness_v22.csv"));

worstSignal = select_worst_signal(cfg, budgetTable, baselineTable, ...
    cfg.architectures(2));
nonidealTable = build_nonideal_table(cfg, worstSignal);
writetable(nonidealTable, fullfile(tableDir, ...
    "table_native_adc_nonideal_v22.csv"));
multicycleTable = build_multicycle_table(cfg, worstSignal);
writetable(multicycleTable, fullfile(tableDir, ...
    "table_multicycle_gain_v22.csv"));
[blindTable, comparisonTable, voltageTable] = build_blind_tables(cfg, ...
    budgetTable, baselineTable, geometryTable, codeTable);
writetable(blindTable, fullfile(tableDir, ...
    "table_health_blind_adc_v22.csv"));
writetable(comparisonTable, fullfile(tableDir, ...
    "table_native_vs_external_v22.csv"));
writetable(voltageTable, fullfile(tableDir, ...
    "table_voltage_architecture_v22.csv"));
metricsTable = build_result_metrics(cfg, comparisonTable, geometryTable, ...
    budgetTable, currentRangeTable);
writetable(metricsTable, fullfile(tableDir, "result_metrics_v22.csv"));
writetable(metricsTable, fullfile(v22Root, "result_metrics_v22.csv"));

v22_generate_figures(v22Root, cfg, budgetTable, codeTable, geometryTable, ...
    voltageTable, nonidealTable, multicycleTable, kRTable, comparisonTable);
summary = struct("targetStatus", cfg.targetStatus, ...
    "profileRows", height(profileTable), "budgetRows", height(budgetTable), ...
    "geometryRows", height(geometryTable), "codeRows", height(codeTable), ...
    "nonidealRows", height(nonidealTable), ...
    "multicycleRows", height(multicycleTable), ...
    "kRRows", height(kRTable), "blindRows", height(blindTable), ...
    "comparisonRows", height(comparisonTable), ...
    "recommendedNativeAccuracyPassFraction", comparisonTable.accuracy_pass_fraction( ...
        comparisonTable.path_id == "native_12_V2"));
save(fullfile(rawDir, "v22_all_results.mat"), "summary", "cfg", ...
    "profileTable", "baselineTable", "budgetTable", "currentRangeTable", ...
    "geometryTable", "codeTable", "kRTable", "nonidealTable", ...
    "multicycleTable", "blindTable", "comparisonTable", "voltageTable", ...
    "metricsTable", "-v7.3");
fprintf("v2.2 pipeline complete: %d blind rows, native V2 accuracy pass %.1f%%.\n", ...
    height(blindTable), 100 * summary.recommendedNativeAccuracyPassFraction);
end

