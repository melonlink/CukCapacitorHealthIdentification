function T = build_result_metrics(cfg, comparison, geometry, budget, currentRange)
n = height(comparison);
rows = cell(n, 18);
for k = 1:n
    z = comparison(k, :);
    rows(k, :) = {"ADC_PATH_" + z.path_id, "native_vs_external", ...
        z.path_id, z.ADC_mode, z.voltage_architecture, z.nominal_bits, ...
        z.ENOB, z.fs_adc_Hz, z.multi_cycle, z.C_MAPE_worst_percent, ...
        z.ESR_MAPE_worst_percent, z.accuracy_pass_fraction, ...
        z.confidence_pass_fraction, z.geometry_pass_fraction, ...
        z.meets_95_percent_blind_accuracy, cfg.targetStatus, ...
        cfg.primaryCalibration, z.role};
end
names = ["test_id" "category" "path_id" "ADC_mode" ...
    "voltage_architecture" "nominal_bits" "ENOB" "fs_adc_Hz" ...
    "multi_cycle" "C_MAPE_worst_percent" "ESR_MAPE_worst_percent" ...
    "blind_accuracy_pass_fraction" "confidence_pass_fraction" ...
    "sampling_geometry_pass_fraction" "status" "target_DSP_status" ...
    "calibration_level" "notes"];
T = cell2table(rows, VariableNames=names);
T.minimum_edge_signal_mV(:) = min(budget.edge_ESR_signal_mV);
T.minimum_charge_signal_mV(:) = min(budget.charge_C_signal_mV);
T.recommended_current_full_scale_A(:) = currentRange.engineering_full_scale_A(2);
T.selected_geometry_count(:) = sum(geometry.selected);
end
