        baseline, geometry, codeTable)
paths = path_definitions(cfg);
n = numel(paths) * height(budget);
rows = cell(n, 34);
row = 0;
for p = 1:numel(paths)
    path = paths(p);
    profile = cfg.profiles(path.profileIndex);
    arch = cfg.architectures(path.archIndex);
    selected = geometry.selected & geometry.fs_adc_Hz == profile.fsHz;
    geometryPass = any(selected);
    if geometryPass
        g = geometry.guard_us(selected);
        W = geometry.window_us(selected);
        Nw = geometry.points_required_per_side(selected);
    else
        g = NaN;
        W = NaN;
        Nw = NaN;
    end
    for k = 1:height(budget)
        signal = make_signal(cfg, budget(k, :), baseline, arch);
        cal = cfg.calibrations(4);
        m = v22_adc_observation_mc(signal, profile, arch, ...
            cfg.primaryCycles, cfg.primaryNoiseCase, cal, ...
            cfg.primaryFusion, cfg.blindSeeds, 400000 + k * 100, cfg);
        row = row + 1;
        rows(row, :) = {path.id, profile.name, arch.id, profile.bits, ...
            profile.enob, profile.fsHz, budget.operating_case(k), ...
            budget.Vin(k), budget.D(k), budget.load(k), budget.C(k), ...
            budget.ESR(k), budget.I_sum(k), ...
            budget.edge_ESR_signal_mV(k), budget.charge_C_signal_mV(k), ...
            cfg.currentRangeA, cfg.primaryCycles, cfg.primaryCalibration, ...
