    values{12} = 0;
    values{13} = 0;
    values{14} = 0;
    values{16} = 0;
end
if type == "ENOB_sweep"
    values{7} = 2;
end
if profile.type == "native_reference" && cfg.targetStatus == "TARGET_DSP_NOT_FIXED"
    values{20} = "TARGET_DSP_NOT_FIXED_PARAMETER_SWEEP";
end
end

function T = build_multicycle_table(cfg, worstSignal)
paths = path_definitions(cfg);
noiseCases = ["Q1_deterministic" "Q2_2mV" "Q3_full_nonideal"];
fusions = ["TS_SLTVKE_sequential" "weighted_batch_average" ...
    "robust_trimmed_mean"];
n = numel(paths) * numel(cfg.cycles) * numel(noiseCases) * numel(fusions);
rows = cell(n, 27);
row = 0;
for p = 1:numel(paths)
    path = paths(p);
    profile = cfg.profiles(path.profileIndex);
    arch = cfg.architectures(path.archIndex);
    signal = worstSignal;
    signal.kRTrue = arch.nominalKR * (1 + .01);
    for cycleIndex = 1:numel(cfg.cycles)
        nCycle = cfg.cycles(cycleIndex);
        for noiseIndex = 1:numel(noiseCases)
            noiseCase = noiseCases(noiseIndex);
            for fusionIndex = 1:numel(fusions)
                fusion = fusions(fusionIndex);
                cal = cfg.calibrations(4);
                m = v22_adc_observation_mc(signal, profile, arch, nCycle, ...
                    noiseCase, cal, fusion, cfg.mcSeeds, ...
                    300000 + p * 10000 + noiseIndex * 1000 + ...
                    fusionIndex * 100, cfg);
                row = row + 1;
                rows(row, :) = metric_row(path.id, profile, arch, nCycle, ...
                    noiseCase, cal.name, fusion, m);
            end
        end
    end
end
names = metric_names();
T = cell2table(rows, VariableNames=names);
end

